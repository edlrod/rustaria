// Generates the `Tile` enum from `assets/tiles.toml`.

use std::collections::HashSet;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let config_path = manifest_dir.join("assets/tiles.toml");
    println!("cargo:rerun-if-changed={}", config_path.display());

    let source = fs::read_to_string(&config_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", config_path.display()));
    let value: toml::Value = toml::from_str(&source)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", config_path.display()));

    let entries = value
        .get("tile")
        .and_then(|v| v.as_array())
        .unwrap_or_else(|| panic!("{} must contain [[tile]] entries", config_path.display()));

    let names: Vec<String> = entries
        .iter()
        .map(|entry| {
            entry
                .get("name")
                .and_then(|v| v.as_str())
                .unwrap_or_else(|| panic!("every [[tile]] entry needs a string 'name'"))
                .to_string()
        })
        .collect();

    let mut seen = HashSet::new();
    let variants: Vec<String> = names
        .iter()
        .map(|name| {
            let variant = to_pascal(name);
            if !is_valid_ident(&variant) {
                panic!("tile name '{name}' does not map to a valid Rust identifier ('{variant}')");
            }
            if !seen.insert(variant.clone()) {
                panic!("tile names collide on Rust identifier '{variant}'");
            }
            variant
        })
        .collect();

    let count = variants.len();
    let mut out =
        String::from("// @generated by build.rs from assets/tiles.toml. Do not edit.\n\n");

    out.push_str(
        "#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\n#[repr(u16)]\npub enum Tile {\n",
    );
    for (i, variant) in variants.iter().enumerate() {
        out.push_str(&format!("    {variant} = {i},\n"));
    }
    out.push_str("}\n\n");

    out.push_str("impl Tile {\n");
    out.push_str(&format!("    pub const COUNT: usize = {count};\n\n"));
    out.push_str(&format!("    pub const ALL: [Tile; {count}] = [\n"));
    for variant in &variants {
        out.push_str(&format!("        Tile::{variant},\n"));
    }
    out.push_str("    ];\n\n");

    out.push_str("    pub const fn name(self) -> &'static str {\n        match self {\n");
    for (variant, name) in variants.iter().zip(&names) {
        out.push_str(&format!("            Tile::{variant} => {name:?},\n"));
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    pub fn from_name(name: &str) -> Option<Tile> {\n        match name {\n");
    for (variant, name) in variants.iter().zip(&names) {
        out.push_str(&format!("            {name:?} => Some(Tile::{variant}),\n"));
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("tiles.rs"), out).unwrap();
}

fn to_pascal(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn is_valid_ident(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}
